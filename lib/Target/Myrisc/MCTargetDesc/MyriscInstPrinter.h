#ifndef LLVM_MYRISCINSTPRINTER_H
#define LLVM_MYRISCINSTPRINTER_H

#include "MCTargetDesc/MyriscMCTargetDesc.h"
#include "llvm/MC/MCInstPrinter.h"
#include "llvm/MC/MCRegister.h"
namespace llvm {
class MyriscInstPrinter : public MCInstPrinter {
public:
  MyriscInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}
  void printMemOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printPtrOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  void printRegName(raw_ostream &OS, MCRegister Reg) ;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Autogenerated by tblgen.
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  // static const char *getRegisterName(MCRegister Reg);
  const char * getRegisterName(unsigned int) ;

  void printCustomAliasOperand(
         const MCInst *MI, uint64_t Address, unsigned OpIdx,
         unsigned PrintMethodIdx,
         raw_ostream &OS) ;
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);

  std::pair<const char *, uint64_t> getMnemonic(const MCInst *MI)  override;
  ///
private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImmediate(const MCInst *MI, unsigned opNum, raw_ostream &O);
};
} // namespace llvm

#endif // LLVM_MYRISCINSTPRINTER_H
