#ifndef LLVM_MYRISCSUBTARGET_H
#define LLVM_MYRISCSUBTARGET_H

#include "llvm/ADT/Triple.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/Target/TargetMachine.h"
#include "MyriscRegisterInfo.h"
#include "MyriscFrameLowering.h"
#include "MyriscISelLowering.h"
#include "MyriscInstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/MC/MCInstrItineraries.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "MyriscGenSubtargetInfo.inc"


namespace llvm {
class StringRef;

class MyriscTargetMachine;

class MyriscSubtarget : public MyriscGenSubtargetInfo {

protected:



  const MyriscTargetMachine &TM;

  Triple TargetTriple;

  const SelectionDAGTargetInfo TSInfo;
  //
  const MyriscInstrInfo InstrInfo;
  MyriscRegisterInfo RegInfo;
  MyriscFrameLowering FrameLowering;
  MyriscTargetLowering TLI;

public:

  // This constructor initializes the data members to match that
  // of the specified triple.
  MyriscSubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                 const MyriscTargetMachine &_TM);

  // Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU,StringRef TuneCPU, StringRef FS);


  unsigned stackAlignment() const { return 16; }

  // MyriscSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS,
  //                                                const TargetMachine &TM);

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
  const MyriscInstrInfo* getInstrInfo() const override { return  &InstrInfo; }
  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const MyriscRegisterInfo *getRegisterInfo() const override {
    return &RegInfo;
  }
  const MyriscTargetLowering *getTargetLowering() const override {
    return &TLI;
  }
  MyriscSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS,
                                                 const TargetMachine &TM);
};
} // End llvm namespace

#endif // LLVM_MYRISCSUBTARGET_H
